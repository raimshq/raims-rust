#!/usr/bin/env python3
"""Generate the Rust SDK from its pinned public OpenAPI without network access."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import sys
import subprocess
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "// Generated by scripts/generate.py. Do not edit.\n"
VERBS = {"get", "post", "put", "patch", "delete", "head", "options", "trace"}
SCHEMA_KEYS = {
    "$ref", "type", "format", "properties", "required", "items",
    "additionalProperties", "minimum", "maximum", "exclusiveMinimum",
    "exclusiveMaximum", "minLength", "maxLength", "minItems", "maxItems",
    "minProperties", "maxProperties", "propertyNames", "pattern", "enum",
    "const", "anyOf", "oneOf", "allOf", "uniqueItems", "nullable",
    "x-raims-enum-labels", "x-raims-max-utf8-bytes", "contentEncoding", "contentMediaType",
}
DOCUMENTATION_KEYS = {
    "title", "description", "example", "examples", "default", "deprecated",
    "readOnly", "writeOnly", "externalDocs", "xml", "$schema", "$id",
}


def read_json(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def snake(value):
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", value)
    return value.lower()


def pascal(value):
    value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode()
    return "".join(part[:1].upper() + part[1:] for part in re.findall(r"[A-Za-z0-9]+", value))


def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError("A public identifier cannot be represented in Rust: " + repr(value))
    return value


def resolve(spec, value):
    seen = set()
    while "$ref" in value:
        reference = value["$ref"]
        if not reference.startswith("#/") or reference in seen:
            raise ValueError("Only non-circular local object references are supported.")
        seen.add(reference)
        target = spec
        for part in reference[2:].split("/"):
            target = target[part.replace("~1", "/").replace("~0", "~")]
        value = target
    return value


def compact(schema):
    if not isinstance(schema, dict):
        raise TypeError("Every schema must be an object.")
    if "allOf" in schema or "oneOf" in schema:
        raise ValueError("allOf and oneOf schemas are not supported by response hydration.")
    if "anyOf" in schema:
        variants = schema["anyOf"]
        if not isinstance(variants, list) or len(variants) != 2 or not all(isinstance(part, dict) for part in variants) or sum(part.get("type") == "null" for part in variants) != 1:
            raise ValueError("Only nullable anyOf schemas are supported.")
    kinds = schema.get("type")
    if isinstance(kinds, list) and (not kinds or len(kinds) != len(set(kinds)) or len([kind for kind in kinds if kind != "null"]) > 1):
        raise ValueError("Only a single schema type with optional null is supported.")
    unknown = set(schema) - SCHEMA_KEYS - DOCUMENTATION_KEYS
    if unknown:
        raise ValueError("Unsupported schema keywords: " + ", ".join(sorted(unknown)))
    result = {}
    for key, value in schema.items():
        if key not in SCHEMA_KEYS:
            continue
        if key == "properties":
            result[key] = {name: compact(child) for name, child in value.items()}
        elif key in {"items", "propertyNames"} or key == "additionalProperties" and isinstance(value, dict):
            result[key] = compact(value)
        elif key in {"anyOf", "oneOf", "allOf"}:
            result[key] = [compact(child) for child in value]
        else:
            result[key] = copy.deepcopy(value)
    return result


def flatten_object(schema, schemas):
    """Resolve object composition for annotations without weakening validation metadata."""
    if "$ref" in schema:
        return flatten_object(schemas[schema["$ref"].rsplit("/", 1)[-1]], schemas)
    if "allOf" in schema:
        merged = {"type": "object", "properties": {}, "required": []}
        for part in schema["allOf"]:
            item = flatten_object(part, schemas)
            if item.get("type") != "object":
                raise ValueError("Only object allOf compositions can be represented.")
            for key, value in item.get("properties", {}).items():
                if key in merged["properties"] and merged["properties"][key] != value:
                    raise ValueError("Conflicting allOf properties cannot be represented.")
                merged["properties"][key] = value
            merged["required"].extend(item.get("required", []))
        return merged
    return schema


def object_type(schema):
    types = schema.get("type")
    return types == "object" or isinstance(types, list) and "object" in types


def normalize_schema(schema, suggested, schemas, hoist=False):
    result = copy.deepcopy(schema)
    for key, value in schema.items():
        if key == "properties":
            result[key] = {name: normalize_schema(child, suggested + pascal(name), schemas, True) for name, child in value.items()}
        elif key in {"items", "additionalProperties"} and isinstance(value, dict):
            result[key] = normalize_schema(value, suggested + "Item", schemas, True)
        elif key in {"anyOf", "oneOf", "allOf"}:
            result[key] = [normalize_schema(part, suggested + "Variant" + str(i + 1), schemas, True) for i, part in enumerate(value)]
    if hoist and object_type(result) and result.get("properties"):
        nullable = result.get("nullable") or isinstance(result.get("type"), list) and "null" in result["type"]
        model = dict(result, type="object")
        model.pop("nullable", None)
        if suggested in schemas and schemas[suggested] != model:
            raise ValueError("Inline schema name collision: " + suggested)
        identifier(suggested)
        schemas[suggested] = model
        reference = {"$ref": "#/components/schemas/" + suggested}
        return {"anyOf": [reference, {"type": "null"}]} if nullable else reference
    return result


def normalized_schemas(spec):
    schemas = {name: compact(schema) for name, schema in spec["components"]["schemas"].items()}
    for name in schemas:
        identifier(name)
    for name in list(schemas):
        schemas[name] = normalize_schema(schemas[name], name, schemas)
    return schemas


def refs(schema):
    result = set()
    if isinstance(schema, dict):
        if "$ref" in schema:
            reference = schema["$ref"]
            if not reference.startswith("#/components/schemas/"):
                raise ValueError("Schema references must target components.schemas.")
            result.add(reference.rsplit("/", 1)[-1])
        for value in schema.values():
            result.update(refs(value))
    elif isinstance(schema, list):
        for value in schema:
            result.update(refs(value))
    return result


def reachable(roots, schemas):
    result = set()
    for root in roots:
        result.update(refs(root))
    pending = list(result)
    while pending:
        name = pending.pop()
        if name not in schemas:
            raise ValueError("Unresolved schema: " + name)
        for child in refs(schemas[name]):
            if child not in result:
                result.add(child)
                pending.append(child)
    return result


def resolved_value_schema(schema, schemas):
    seen = set()
    while "$ref" in schema or nullable(schema):
        if "$ref" in schema:
            reference = schema["$ref"]
            if not reference.startswith("#/components/schemas/") or reference in seen:
                raise ValueError("Only non-circular local value references are supported.")
            seen.add(reference)
            schema = schemas[reference.rsplit("/", 1)[-1]]
        else:
            schema = nonnullable(schema)
    return schema


def validate_query_parameter(parameter, schemas):
    schema = resolved_value_schema(compact(parameter["schema"]), schemas)
    if schema.get("type") not in {"string", "integer", "number", "boolean"}:
        raise ValueError("Query arrays and objects require explicit serialization support: " + parameter["name"])
    if parameter.get("style", "form") != "form":
        raise ValueError("Only form-style scalar query parameters are supported: " + parameter["name"])
    if "explode" in parameter and not isinstance(parameter["explode"], bool):
        raise ValueError("Query explode must be a boolean: " + parameter["name"])
    if parameter.get("allowReserved", False) is not False:
        raise ValueError("Reserved query values require explicit serialization support: " + parameter["name"])


def collect_operations(spec, source, schemas):
    operations = {}
    input_roots = []
    response_roots = []
    for path, item in spec["paths"].items():
        if not path.startswith("/v1/"):
            raise ValueError("Only versioned public product endpoints can be generated.")
        for verb, operation in item.items():
            if verb not in VERBS:
                continue
            name = identifier(operation.get("operationId"))
            if name in operations:
                raise ValueError("Operation IDs must be unique.")
            if operation.get("x-raims-availability", "production") != "production":
                raise ValueError("An operation has not been published.")
            security = operation.get("security", spec.get("security", []))
            if {"BearerAuth": []} not in security:
                raise ValueError("An operation does not support API key authentication.")
            parameters = [resolve(spec, p) for p in item.get("parameters", []) + operation.get("parameters", [])]
            identities = [(p["in"], p["name"]) for p in parameters]
            if len(identities) != len(set(identities)):
                raise ValueError("Duplicate parameter definitions cannot be represented.")
            if any(p["in"] not in {"path", "query", "header"} for p in parameters):
                raise ValueError("Unsupported public parameter location.")
            query_parameters = [p for p in parameters if p["in"] == "query"]
            for parameter in query_parameters:
                validate_query_parameter(parameter, schemas)
            for parameter in parameters:
                oauth_only = parameter.get("x-raims-authentication") == "oauth" or parameter.get("x-raims-security-schemes") == ["ApplicationOAuth"]
                if parameter["in"] == "header" and parameter["name"] != "Idempotency-Key" and not oauth_only:
                    raise ValueError("Unsupported public header parameter: " + parameter["name"])
            path_params = re.findall(r"\{([^}]+)\}", path)
            for param in path_params:
                identifier(param)
                if not any(p["in"] == "path" and p["name"] == param and p.get("required") for p in parameters):
                    raise ValueError("Every path placeholder requires a declared path parameter.")
            request_body = resolve(spec, operation["requestBody"]) if operation.get("requestBody") else None
            body_schema = request_body.get("content", {}).get("application/json", {}).get("schema") if request_body else None
            if request_body and not body_schema:
                raise ValueError("Only JSON request bodies can be generated.")
            if body_schema and query_parameters:
                raise ValueError("Combined query and body parameters require explicit generator support.")
            if set(path_params) != {p["name"] for p in parameters if p["in"] == "path"}:
                raise ValueError("Path parameters must match the public path placeholders.")
            query_schema = {
                "type": "object", "properties": {p["name"]: compact(p["schema"]) for p in query_parameters},
                "required": [p["name"] for p in query_parameters if p.get("required")],
            }
            params_schema = normalize_schema(compact(body_schema), name + "RequestBody", schemas, True) if body_schema else normalize_schema(query_schema, name + "Params", schemas)
            responses = {}
            for status, response in operation["responses"].items():
                response = resolve(spec, response)
                content = response.get("content")
                schema = content.get("application/json", {}).get("schema") if content else None
                normalized_response = normalize_schema(compact(schema), name + "Response" + status, schemas, True) if schema else None
                if normalized_response:
                    response_roots.append(normalized_response)
                if not re.fullmatch(r"2\d\d", status):
                    continue
                if content and not schema:
                    raise ValueError("Only JSON success responses can be generated.")
                responses[status] = normalized_response
            if not responses:
                raise ValueError("An operation has no declared success response.")
            success_objects = [flatten_object(schema, schemas) for schema in responses.values() if schema]
            paginated = any("list" in value.get("properties", {}) and "page" in value.get("properties", {}) for value in success_objects)
            if paginated and (verb != "get" or any("list" not in value.get("properties", {}) or "page" not in value.get("properties", {}) for value in success_objects) or not {"after", "before"}.issubset(query_schema["properties"])):
                raise ValueError("The cursor pagination contract cannot be represented.")
            input_roots.append(params_schema)
            operations[name] = {
                "id": name, "method": verb.upper(), "path": path, "pathParams": path_params,
                "pathSchemas": {p["name"]: compact(p["schema"]) for p in parameters if p["in"] == "path"},
                "query": query_schema["properties"], "body": bool(body_schema),
                "body_required": bool(request_body and request_body.get("required")),
                "params_schema": params_schema,
                "idempotency": any(p["in"] == "header" and p["name"] == "Idempotency-Key" for p in parameters),
                "maxBodyBytes": operation.get("x-raims-max-body-bytes"),
                "responses": responses, "paginated": paginated,
                "summary": " ".join(operation.get("summary", name).split()),
            }
    if len(operations) != source["operations"] or spec["info"]["version"] != source["api_version"]:
        raise ValueError("The operation count or API version differs from source.json.")
    return operations, reachable(input_roots, schemas), reachable(response_roots, schemas)


def enum_constants(schemas):
    constants = {}

    def add(name, value):
        if name in constants and constants[name] != value:
            raise ValueError("An enum constant name collides: " + name)
        constants[name] = value

    def walk(schema, path):
        if schema.get("enum"):
            values = schema["enum"]
            labels = schema.get("x-raims-enum-labels")
            if labels is not None and (len(labels) != len(values) or not all(isinstance(label, str) for label in labels)):
                raise ValueError("Explicit enum labels must match their values.")
            for index, value in enumerate(values):
                label = labels[index] if labels else value if isinstance(value, str) else None
                if label is None:
                    continue
                name = re.sub(r"[^A-Z0-9]+", "_", snake(path + "_" + str(label)).upper()).strip("_")
                identifier(name)
                add(name, value)
        for field, child in schema.get("properties", {}).items():
            walk(child, path + "_" + field)
        for key in ("items", "additionalProperties"):
            if isinstance(schema.get(key), dict):
                walk(schema[key], path + "_item")
        for key in ("anyOf", "oneOf", "allOf"):
            for child in schema.get(key, []):
                walk(child, path)

    for name, schema in schemas.items():
        walk(schema, name)
    return constants


def reference_translations():
    catalog = read_json("docs/reference.en.json")
    translations = catalog.get("translations")
    if catalog.get("locale") != "en" or not isinstance(translations, dict):
        raise ValueError("The reference requires an English editorial translation catalog.")
    if any(not isinstance(source, str) or not source or not isinstance(target, str) or not target.strip()
           for source, target in translations.items()):
        raise ValueError("Reference translations must map exact nonempty source text to English text.")
    return translations


def reference_text(source, translations):
    if not source:
        return ""
    if source not in translations:
        raise ValueError("Missing English reference translation for exact source: " + repr(source))
    return " ".join(translations[source].split())


RUST_KEYWORDS = set("as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box do final macro override priv typeof unsized virtual yield try gen".split())


def rust_field(value):
    identifier(value)
    if value in {"self", "Self", "super", "crate"}:
        raise ValueError("A public field cannot use a reserved Rust path identifier: " + value)
    return "r#" + value if value in RUST_KEYWORDS else value


def nullable(schema):
    if schema.get("nullable"):
        return True
    if isinstance(schema.get("type"), list):
        return "null" in schema["type"]
    return any(part.get("type") == "null" for part in schema.get("anyOf", []))


def nonnullable(schema):
    schema = dict(schema)
    schema.pop("nullable", None)
    if isinstance(schema.get("type"), list):
        schema["type"] = next(kind for kind in schema["type"] if kind != "null")
    if "anyOf" in schema:
        schema = next(part for part in schema["anyOf"] if part.get("type") != "null")
    return schema


def rust_type(schema, schemas, qualify=False, strip_null=False):
    if nullable(schema):
        inner = rust_type(nonnullable(schema), schemas, qualify)
        return inner if strip_null else "Option<" + inner + ">"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        if name not in schemas:
            raise ValueError("Unresolved schema: " + name)
        return ("models::" if qualify else "") + name
    kind = schema.get("type")
    if kind == "array":
        return "Vec<" + rust_type(schema.get("items", {}), schemas, qualify) + ">"
    if kind == "object" or "properties" in schema:
        if schema.get("properties"):
            raise ValueError("Inline objects must be normalized into named Rust types.")
        item = schema.get("additionalProperties")
        return "BTreeMap<String, " + (rust_type(item, schemas, qualify) if isinstance(item, dict) else "serde_json::Value") + ">"
    if kind == "null":
        return "()"
    result = {"integer": "i64", "number": "serde_json::Number", "string": "String", "boolean": "bool"}.get(kind)
    if result:
        return result
    if not schema:
        return "serde_json::Value"
    raise ValueError("A schema has no representable Rust type: " + repr(schema))


def debug_impl(name):
    return "impl std::fmt::Debug for " + name + " {\n    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { f.write_str(\"" + name + " { .. }\") }\n}\n"


def response_deserializer(name, fields):
    lines = ["impl<'de> serde::Deserialize<'de> for " + name + " {",
             "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {",
             "        struct ResponseVisitor;",
             "        impl<'de> serde::de::Visitor<'de> for ResponseVisitor {",
             "            type Value = " + name + ";",
             "            fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
             "                formatter.write_str(\"a response object\")",
             "            }",
             "            fn visit_map<M: serde::de::MapAccess<'de>>(self, mut map: M) -> Result<Self::Value, M::Error> {"]
    for index, (_, annotation, _) in enumerate(fields):
        lines.append("                let mut field_" + str(index) + ": Option<" + annotation + "> = None;")
    lines.extend(["                let mut extra_fields = BTreeMap::new();",
                  "                while let Some(key) = map.next_key::<String>()? {",
                  "                    match key.as_str() {"])
    for index, (field, _, _) in enumerate(fields):
        variable = "field_" + str(index)
        literal = json.dumps(field)
        lines.extend(["                        " + literal + " => {",
                      "                            if " + variable + ".is_some() { return Err(serde::de::Error::duplicate_field(" + literal + ")); }",
                      "                            " + variable + " = Some(map.next_value()?);",
                      "                        }"])
    lines.extend(["                        _ => { extra_fields.insert(key, map.next_value::<serde_json::Value>()?); }",
                  "                    }",
                  "                }",
                  "                Ok(" + name + " {"])
    for index, (field, _, default) in enumerate(fields):
        value = "field_" + str(index)
        value += ".unwrap_or_default()" if default else ".ok_or_else(|| <M::Error as serde::de::Error>::missing_field(" + json.dumps(field) + "))?"
        lines.append("                    " + rust_field(field) + ": " + value + ",")
    lines.extend(["                    extra_fields,", "                })", "            }", "        }",
                  "        deserializer.deserialize_map(ResponseVisitor)", "    }", "}"])
    return "\n".join(lines)


def object_definition(name, schema, schemas, inputs):
    schema = flatten_object(schema, schemas)
    if not object_type(schema):
        return "pub type " + name + " = " + rust_type(schema, schemas) + ";\n"
    properties = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not required.issubset(properties):
        raise ValueError("A required property is not declared.")
    if "extra_fields" in properties and not inputs:
        raise ValueError("The public property collides with response field storage.")
    derives = "Clone, Default, serde::Serialize, serde::Deserialize" if inputs else "Clone, serde::Serialize"
    lines = ["#[derive(" + derives + ")]", "pub struct " + name + " {"]
    response_fields = []
    for field, child in properties.items():
        annotation = rust_type(child, schemas, strip_null=inputs)
        if inputs:
            lines.extend(["    #[serde(default, skip_serializing_if = \"Optional::is_unset\")]", "    pub " + rust_field(field) + ": Optional<" + annotation + ">,"])
        else:
            if field not in required and not annotation.startswith("Option<"):
                annotation = "Option<" + annotation + ">"
            default = field not in required or nullable(child)
            if default:
                lines.append("    #[serde(default)]")
            lines.append("    pub " + rust_field(field) + ": " + annotation + ",")
            response_fields.append((field, annotation, default))
    if not inputs:
        lines.extend(["    #[serde(default, flatten)]", "    pub extra_fields: BTreeMap<String, serde_json::Value>,"])
    lines.extend(["}", "", debug_impl(name)])
    if not inputs:
        lines.append(response_deserializer(name, response_fields))
    return "\n".join(lines)


def validate_input_object(name, schema, schemas):
    schema = resolved_value_schema(schema, schemas)
    if object_type(schema) and schema.get("additionalProperties", True) is not False:
        raise ValueError("Named and body input objects with additional properties require explicit representation support: " + name)


def generate_params(operations, schemas, names):
    lines = [HEADER, "use std::collections::BTreeMap;\nuse crate::Optional;\n"]
    for name in sorted(names):
        validate_input_object(name, schemas[name], schemas)
        lines.append(object_definition(name, schemas[name], schemas, True))
    for name, operation in operations.items():
        if operation["body"] or operation["query"]:
            param_name = name + "Params"
            if param_name in names:
                raise ValueError("Operation parameters collide with a named input: " + param_name)
            if operation["body"]:
                validate_input_object(param_name, operation["params_schema"], schemas)
            lines.append(object_definition(param_name, operation["params_schema"], schemas, True))
    return "\n".join(lines)


def variants(operation, schemas):
    result = []
    for status, schema in operation["responses"].items():
        kind = rust_type(schema, schemas) if schema else "()"
        if kind not in [item[1] for item in result]:
            result.append((status, kind, schema))
    return result


def response_type(operation, schemas, qualify=False):
    choices = variants(operation, schemas)
    if len(choices) == 1:
        return rust_type(choices[0][2], schemas, qualify) if choices[0][2] else "()"
    name = operation["id"] + "Response"
    if qualify and name != "()":
        return "models::" + name
    return name


def generate_models(schemas, names, operations):
    lines = [HEADER, "use std::collections::BTreeMap;\n"]
    for name in sorted(names):
        lines.append(object_definition(name, schemas[name], schemas, False))
    for operation in operations.values():
        choices = variants(operation, schemas)
        if len(choices) < 2:
            continue
        name = operation["id"] + "Response"
        if name in names:
            raise ValueError("The result union collides with a response model: " + name)
        lines.extend(["#[derive(Clone, serde::Serialize)]", "#[serde(untagged)]", "pub enum " + name + " {"])
        for status, kind, _ in choices:
            lines.append("    Status" + status + "(" + kind + "),")
        lines.extend(["}", debug_impl(name), "impl<'de> serde::Deserialize<'de> for " + name + " {", "    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {", "        let value = <serde_json::Value as serde::Deserialize>::deserialize(deserializer)?;"])
        for status, kind, schema in choices:
            resolved = flatten_object(schema, schemas) if schema else {}
            constants = [(field, child["const"]) for field, child in resolved.get("properties", {}).items() if "const" in child]
            if not constants:
                raise ValueError("Distinct success types require published constant discriminators: " + operation["id"])
            condition = " && ".join("value.get(" + json.dumps(field) + ") == Some(&serde_json::json!(" + json.dumps(value) + "))" for field, value in constants)
            lines.append("        if " + condition + " { return serde_json::from_value(value).map(Self::Status" + status + ").map_err(|_| serde::de::Error::custom(\"Invalid response shape.\")); }")
        lines.extend(["        Err(serde::de::Error::custom(\"No declared success response matches the result.\"))", "    }", "}"])
    return "\n".join(lines)


def service_name(value):
    return pascal(value) + "Service"


def generate_services(services, operations, schemas, translations):
    lines = [HEADER, "use crate::{ApiResponse, Error, RaimsClient, RequestOptions, Pager};\nuse crate::{models, params};\n", "impl RaimsClient {"]
    for service in services:
        if service.startswith("simulation_"):
            continue
        lines.append("    pub fn " + service + "(&self) -> " + service_name(service) + "<'_> { " + service_name(service) + " { client: self } }")
    lines.extend(["    pub fn simulations(&self) -> SimulationsService<'_> { SimulationsService { client: self } }", "}", "#[derive(Clone, Copy)]", "pub struct SimulationsService<'a> { client: &'a RaimsClient }", "impl<'a> SimulationsService<'a> {", "    pub fn charges(&self) -> SimulationChargesService<'a> { SimulationChargesService { client: self.client } }", "    pub fn refunds(&self) -> SimulationRefundsService<'a> { SimulationRefundsService { client: self.client } }", "}"])
    for service, methods in services.items():
        name = service_name(service)
        lines.extend(["#[derive(Clone, Copy)]", "pub struct " + name + "<'a> { client: &'a RaimsClient }", "impl " + name + "<'_> {"])
        for method, operation_id in methods.items():
            op = operations[operation_id]
            has_params = op["body"] or bool(op["query"])
            fields = [rust_field(field) for field in op["pathParams"]]
            args = ["&self"] + [field + ": &str" for field in fields]
            calls = fields[:]
            if has_params:
                args.append("params: &params::" + operation_id + "Params")
                calls.append("params")
            result = "Result<ApiResponse<" + response_type(op, schemas, True) + ">, Error>"
            summary = reference_text(op["summary"], translations)
            lines.extend(["    /// " + summary.rstrip(".") + ".", "    pub async fn " + rust_field(method) + "(" + ", ".join(args) + ") -> " + result + " {", "        self." + method + "_with_options(" + ", ".join(calls + ["&RequestOptions::default()"]) + ").await", "    }"])
            path = "&[" + ", ".join("(" + json.dumps(field) + ", " + rust_field(field) + ")" for field in op["pathParams"]) + "]"
            lines.extend(["    /// " + summary.rstrip(".") + ", using explicit request options.", "    pub async fn " + method + "_with_options(" + ", ".join(args + ["options: &RequestOptions"]) + ") -> " + result + " {", "        self.client.request(" + json.dumps(operation_id) + ", " + path + ", " + ("params" if has_params else "&serde_json::json!({})") + ", options).await", "    }"])
            if op["paginated"]:
                result = "Result<Pager<" + response_type(op, schemas, True) + ">, Error>"
                owned_path = "vec![" + ", ".join("(" + json.dumps(field) + ".to_owned(), " + rust_field(field) + ".to_owned())" for field in op["pathParams"]) + "]"
                lines.extend(["    /// Create a lazy pager that preserves this operation's filters.", "    pub fn " + method + "_pages(" + ", ".join(args) + ") -> " + result + " {", "        self." + method + "_pages_with_options(" + ", ".join(calls + ["&RequestOptions::default()"]) + ")", "    }", "    /// Create a lazy pager with explicit request options.", "    pub fn " + method + "_pages_with_options(" + ", ".join(args + ["options: &RequestOptions"]) + ") -> " + result + " {", "        let params = serde_json::to_value(params).map_err(|_| Error::validation(\"Request parameters cannot be serialized.\"))?;", "        Pager::new(self.client.clone(), " + json.dumps(operation_id) + ", " + owned_path + ", params, options.clone())", "    }"])
        lines.append("}")
    return "\n".join(lines) + "\n"


def generate_constants(constants):
    lines = [HEADER]
    for name, value in sorted(constants.items()):
        if value is None:
            lines.append("pub const " + name + ": Option<&str> = None;")
            continue
        kind = "bool" if isinstance(value, bool) else "i64" if isinstance(value, int) else "&str" if isinstance(value, str) else None
        if kind is None:
            raise ValueError("A published enum constant has no Rust representation.")
        lines.append("pub const " + name + ": " + kind + " = " + json.dumps(value) + ";")
    return "\n".join(lines) + "\n"


def generate_reference(source, services, operations, schemas, constants, spec):
    translations = reference_translations()
    lines = ["# Rust SDK reference", "", "Generated from the public contract pinned in `contracts/source.json`.", "", "`RaimsClient` methods are asynchronous. Reuse the client and await each request.", "", "| Service and method | HTTP operation | Input | Response data |", "| --- | --- | --- | --- |"]
    for service, methods in services.items():
        path = "simulations().charges()" if service == "simulation_charges" else "simulations().refunds()" if service == "simulation_refunds" else service + "()"
        for method, name in methods.items():
            operation = operations[name]
            params = "[`" + name + "Params`](#" + name.lower() + "params)" if operation["body"] or operation["query"] else "-"
            lines.append("| `" + path + "." + method + "` | `" + operation["method"] + " " + operation["path"] + "` | " + params + " | `" + response_type(operation, schemas) + "` |")
    lines.extend(["", "Each method returns `ApiResponse<T>` with typed `data`, `last_response` metadata and the original `raw` JSON value. Methods ending in `_with_options` accept `RequestOptions`. Status 202 remains pending and does not start polling.", "", "For cursor lists, `list_pages` creates a lazy `Pager<T>`. `next_page().await` fetches the first page and then advances with the returned cursor; `previous_page().await` navigates back. Filters and options remain attached to the pager. The list response retains its generated `page` type.", "", "Inputs use `Optional::Unset`, `Optional::Null` and `Optional::Value(value)`. Omission and null are separate actions, and null is accepted only where the public contract permits it. Monetary amounts remain integer cents; dates use Unix seconds UTC. Response models accept new fields in `extra_fields` and retain future numeric or string enum values.", "", "## Input parameters", "", "Parameter types are exported in `raims::params`. Every field defaults to `Optional::Unset`. Required fields must be provided before sending a request; validation uses the pinned contract."])
    for name, operation in operations.items():
        if not operation["body"] and not operation["query"]:
            continue
        normalized = flatten_object(operation["params_schema"], schemas)
        raw_operation = spec["paths"][operation["path"]][operation["method"].lower()]
        if operation["body"]:
            raw_body = resolve(spec, raw_operation["requestBody"])
            documented = resolve(spec, raw_body["content"]["application/json"]["schema"]).get("properties", {})
        else:
            item = spec["paths"][operation["path"]]
            documented = {parameter["name"]: parameter for parameter in (resolve(spec, value) for value in item.get("parameters", []) + raw_operation.get("parameters", [])) if parameter["in"] == "query"}
        summary = reference_text(raw_operation.get("summary", name), translations)
        lines.extend(["", "### " + name + "Params", "", summary.rstrip(".") + ".", "", "| Field | Value type | Required | Description |", "| --- | --- | --- | --- |"])
        for field, child in normalized.get("properties", {}).items():
            description = reference_text(documented.get(field, {}).get("description", ""), translations).replace("|", "\\|")
            annotation = rust_type(child, schemas, strip_null=True).replace("|", "\\|")
            lines.append("| `" + field + "` | `" + annotation + "` | " + ("Yes" if field in normalized.get("required", []) else "No") + " | " + (description or "-") + " |")
    lines.extend(["", "## Named public values", "", "Constants in `raims::enum_values` come from public enums. Numeric values receive names only when the contract publishes explicit labels. Response fields keep their underlying types to accept future values.", "", "| Constant | Value |", "| --- | --- |"])
    for name, value in sorted(constants.items()):
        lines.append("| `" + name + "` | `" + str(value).replace("|", "\\|") + "` |")
    return "\n".join(lines) + "\n"


def rustfmt(content):
    process = subprocess.run(["rustfmt", "--edition", "2021", "--emit", "stdout"], input=content.encode("utf-8"), stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if process.returncode:
        raise ValueError("Rust formatting failed: " + process.stderr.decode("utf-8", errors="replace"))
    return process.stdout.decode("utf-8").replace("\r\n", "\n")


def expected_outputs():
    source = read_json("contracts/source.json")
    raw = (ROOT / "contracts/openapi.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != source["sha256"]:
        raise ValueError("The pinned OpenAPI checksum differs from source.json.")
    if not re.fullmatch(r"[0-9a-f]{40}", source["revision"]):
        raise ValueError("The public source must have an immutable Git revision.")
    expected_url = "https://raw.githubusercontent.com/raimshq/openapi/" + source["revision"] + "/latest/openapi.spec3.json"
    if source["repository"] != "https://github.com/raimshq/openapi" or source["url"] != expected_url:
        raise ValueError("The source URL must identify the pinned public contract.")
    spec = json.loads(raw)
    scheme = spec.get("components", {}).get("securitySchemes", {}).get("BearerAuth", {})
    if scheme.get("type") != "http" or scheme.get("scheme") != "bearer":
        raise ValueError("BearerAuth must remain the public API key bearer scheme.")
    schemas = normalized_schemas(spec)
    operations, inputs, responses = collect_operations(spec, source, schemas)
    services = read_json("contracts/service-map.json")
    mapped = []
    for service, methods in services.items():
        identifier(service)
        if service in RUST_KEYWORDS or snake(service) != service:
            raise ValueError("Service names must use representable snake_case.")
        for method, operation in methods.items():
            identifier(method)
            if snake(method) != method or operation not in operations:
                raise ValueError("Service methods must map snake_case names to published operations.")
            mapped.append(operation)
        generated_methods = []
        for method, operation in methods.items():
            generated_methods.extend([method, method + "_with_options"])
            if operations[operation]["paginated"]:
                generated_methods.extend([method + "_pages", method + "_pages_with_options"])
        if len(generated_methods) != len(set(generated_methods)):
            raise ValueError("Generated method names collide within a service.")
    if len(mapped) != len(set(mapped)) or set(mapped) != set(operations):
        raise ValueError("The service map must cover each published operation exactly once.")
    constants = enum_constants(schemas)
    translations = reference_translations()
    metadata = {"source": source, "services": services, "operations": operations, "schemas": schemas}
    outputs = {
        "src/contract_generated.json": json.dumps(metadata, ensure_ascii=False, indent=2) + "\n",
        "src/params_generated.rs": generate_params(operations, schemas, inputs),
        "src/models_generated.rs": generate_models(schemas, responses, operations),
        "src/services_generated.rs": generate_services(services, operations, schemas, translations),
        "src/enum_values_generated.rs": generate_constants(constants),
        "docs/reference.md": generate_reference(source, services, operations, schemas, constants, spec),
    }
    return {path: rustfmt(content) if path.endswith(".rs") else content for path, content in outputs.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without modifying them.")
    args = parser.parse_args()
    outputs = expected_outputs()
    obsolete = sorted(path.relative_to(ROOT).as_posix() for path in (ROOT / "src").glob("*_generated.*") if path.relative_to(ROOT).as_posix() not in outputs)
    if obsolete:
        raise ValueError("Obsolete generated files require explicit review: " + ", ".join(obsolete))
    changed = []
    for relative, content in outputs.items():
        destination = ROOT / relative
        content = content.encode("utf-8")
        if destination.exists() and destination.read_bytes() == content:
            continue
        changed.append(relative)
        if not args.check:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    if args.check and changed:
        print("Generated files differ: " + ", ".join(changed), file=sys.stderr)
        return 1
    print(("Checked" if args.check else "Generated") + " " + str(read_json("contracts/source.json")["operations"]) + " published operations and " + str(len(outputs)) + " deterministic outputs.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (KeyError, TypeError, ValueError, OSError) as error:
        print("Generation failed: " + str(error), file=sys.stderr)
        raise SystemExit(1)
